void imu_update_estimate(void)
{
  if (MPU6050_ReadData(&mpu, &imu_data) != HAL_OK) {
    return;
  }

  // Update orientation and position every 10 ms.
  IMU_Update(&estimate, &imu_data, IMU_DT);

  // Accumulate calibrated angular velocities (deg/s).
  sum_gx += imu_data.gx;
  sum_gy += imu_data.gy;
  sum_gz += imu_data.gz;

  if (++counter >= 5) {
    int len = snprintf(
        uart_buffer,
        sizeof(uart_buffer),
        "R=%.2f,P=%.2f,Y=%.2f\r\n",
        (double)estimate.roll,
        (double)estimate.pitch,
        (double)estimate.yaw
    );

    if (len > 0 && len < (int)sizeof(uart_buffer)) {
      HAL_UART_Transmit(
          &huart2,
          (uint8_t *)uart_buffer,
          (uint16_t)len,
          10
      );
    }

    sum_gx = 0.0f;
    sum_gy = 0.0f;
    sum_gz = 0.0f;
    counter = 0;
  }
}
bool button_pressed_event(void)
{
  if (!button_irq_pending)
    return false;

  uint32_t now = HAL_GetTick();

  if ((uint32_t)(now - button_irq_time) < DEBOUNCE_MS)
    return false;

  // Briefly protect the shared state while consuming the event.
  __disable_irq();
  button_irq_pending = 0;
  __enable_irq();

  GPIO_PinState current =
      HAL_GPIO_ReadPin(GPIOC, BUTTON_PIN);

  if (current != stable_state)
  {
    stable_state = current;

    if (current == GPIO_PIN_SET)
      return true;
  }

  return false;
}
