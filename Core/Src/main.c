void calibration_sequence() {
  HAL_UART_Transmit(&huart2,"c1\n", 3, 2);
  HAL_Delay(500);
  if (MPU6050_Calibrate(
          &mpu,
          MPU6050_CALIBRATION_SAMPLES
      ) != HAL_OK) {
    Error_Handler();
      }
  HAL_UART_Transmit(&huart2,"c0\n", 3, 2);

}
